export type Difficulty = 1 | 2 | 3;

export type ReviewOutcome = 'remembered' | 'confused' | 'forgotten';

export type SubjectCategory = '영어' | '통합과학' | '한국사' | '수학' | '국어' | '기타';

export type LearningCluster = 'vocab' | 'concept' | 'formula';

export interface ClozeQuiz {
  question: string;
  answer: string;
  hint: string;
  explanation: string;
}

export interface StudyCard {
  id: string;
  subject: SubjectCategory;
  title: string;
  note: string;
  difficulty: Difficulty;
  /** Elapsed time since last learning/review in days */
  elapsedDays: number;
  reviewCount: number;
  lastOutcome: ReviewOutcome | null;
  lastReviewedAt: string;
  /** Clustering category for cold-start curve calibration */
  cluster?: LearningCluster;
  clusterReason?: string;
  /** Gemini NLP difficulty assessment rationale */
  aiDifficultyReason?: string;
  /** Estimated review duration in minutes */
  estimatedMinutes?: number;
  /** Custom fill-in-the-blank quiz generated by Gemini or curated */
  clozeQuiz?: ClozeQuiz;
  /** Number of unresolved blank-page weakness points */
  unresolvedWeaknessCount?: number;
  /** Weighted severity score of unresolved weak points */
  weaknessSeverityScore?: number;
}

export type WeaknessSeverity = 'high' | 'medium';

export interface StructuredWeakPointDraft {
  id?: string;
  concept: string;
  detail: string;
  severity: WeaknessSeverity;
}

export interface WeaknessPointItem {
  id: string;
  cardId: string;
  cardTitle: string;
  subject: SubjectCategory;
  concept: string;
  detail: string;
  severity: WeaknessSeverity;
  resolved: boolean;
  attemptCount: number;
  createdAtLabel: string;
  resolvedAtLabel?: string;
}

export interface QuizSource {
  title: string;
  uri: string;
}

export interface QuizQuestion {
  id: string;
  difficulty: Difficulty;
  question: string;
  options: string[];
  correctIndex: number;
  explanation: string;
}

export interface QuizBundle {
  conceptSummary: string;
  questions: QuizQuestion[];
  sources: QuizSource[];
  generatedBy: string;
}

export interface GeminiCardAnalysis {
  subject: SubjectCategory;
  title: string;
  note: string;
  cluster: LearningCluster;
  clusterReason: string;
  difficulty: Difficulty;
  difficultyReason: string;
  estimatedMinutes: number;
  clozeQuiz: ClozeQuiz;
  extractedText?: string;
  generatedBy: string;
}

export interface MLPWeights {
  /** Input (4) -> Hidden (4) weights: w1[inputIdx][hiddenIdx] */
  w1: number[][];
  /** Hidden (4) biases */
  b1: number[];
  /** Hidden (4) -> Output (1) weights */
  w2: number[];
  /** Output bias */
  b2: number;
}

export interface MLPForwardResult {
  inputs: [number, number, number, number];
  z1: [number, number, number, number];
  hidden: [number, number, number, number];
  z2: number;
  /** Raw tanh output in (-1, 1) representing normalized residual direction */
  output: number;
}

export interface CurvePoint {
  day: number;
  baseRetention: number;
  aiRetention: number;
  residualDelta: number;
}

export interface TrainingLogEntry {
  id: string;
  timestamp: string;
  cardId: string;
  cardTitle: string;
  subject: SubjectCategory;
  outcome: ReviewOutcome;
  difficulty: Difficulty;
  elapsedDays: number;
  reviewCountAfter: number;
  inputs: [number, number, number, number];
  hiddenActivations: [number, number, number, number];
  outputBefore: number;
  outputAfter: number;
  target: number;
  loss: number;
  /** Residual Delta R (%) at t = 1 day before and after this review */
  residualPctBefore: number;
  residualPctAfter: number;
  optimalDayBefore: number;
  optimalDayAfter: number;
  deltaW1: number[][];
  deltaW2: number[];
}

export interface FeedbackBanner {
  id: string;
  cardTitle: string;
  outcome: ReviewOutcome;
  residualPctAfter: number;
  optimalDayBefore: number;
  optimalDayAfter: number;
}

export interface ExamItemEvaluation {
  card: StudyCard;
  cluster: LearningCluster;
  estimatedMinutes: number;
  currentRetentionPct: number;
  examSkipRetentionPct: number;
  examReviewRetentionPct: number;
  /** Expected retention gain on exam day (%p) */
  gainPct: number;
  /** Weighted urgency score per minute (%p/min) */
  efficiencyPerMin: number;
  optimalDropDay: number;
  dropDeadlineCompact: string;
  selected: boolean;
}

export interface ExamOptimizationPlan {
  dDay: number;
  availableMinutes: number;
  usedMinutes: number;
  selectedItems: ExamItemEvaluation[];
  deferredItems: ExamItemEvaluation[];
  /** Average retention across all cards on exam day WITHOUT today's review (%) */
  baselineExamAvgPct: number;
  /** Average retention across all cards on exam day WITH selected reviews (%) */
  optimizedExamAvgPct: number;
  /** Net gain on exam day average (%p) */
  examAvgGainPct: number;
  /** Immediate average retention lift today (%p) */
  immediateAvgBeforePct: number;
  immediateAvgAfterPct: number;
  immediateGainPct: number;
}

export interface BlankPageWeakPointCard {
  title: string;
  note: string;
  difficulty: Difficulty;
  clozeQuiz: ClozeQuiz;
}

export interface BlankPageAnalysis {
  mode: 'full' | 'weakness-retry';
  score: number;
  gradeLabel: '상' | '중' | '하';
  recommendedOutcome: ReviewOutcome;
  rememberedPoints: string[];
  missingPoints: string[];
  structuredMissingPoints: StructuredWeakPointDraft[];
  resolvedWeakPointIds: string[];
  remainingWeakPoints: StructuredWeakPointDraft[];
  feedbackSummary: string;
  weakPointCard?: BlankPageWeakPointCard;
  generatedBy: string;
}

